/**
 * Returns all vehicles in the database
 */
export function getAllVehicles(): VehicleSpec[] {
  return vehicles;
}

/**
 * Retrieves a vehicle by its unique ID
 */
export function getVehicleById(id: string): VehicleSpec | undefined {
  const normalizedId = id.toLowerCase().trim();
  return vehicles.find((v) => v.id.toLowerCase() === normalizedId);
}

/**
 * Searches vehicles by brand or model name
 */
export function searchVehicles(query: string): VehicleSpec[] {
  const q = query.toLowerCase().trim();
  return vehicles.filter(
    (v) =>
      v.brand.toLowerCase().includes(q) ||
      v.model.toLowerCase().includes(q) ||
      v.id.toLowerCase().includes(q) ||
      v.taglineThai.toLowerCase().includes(q)
  );
}

/**
 * Filters vehicles by vehicle category
 */
export function getVehiclesByCategory(category: string): VehicleSpec[] {
  return vehicles.filter((v) => v.category.toLowerCase() === category.toLowerCase());
}
